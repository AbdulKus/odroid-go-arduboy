#!/usr/bin/env python3
"""Generate the firmware glyph bitmaps with Pillow and Liberation Sans."""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def bitmap(font_path, size, codes, name, baseline, height):
    font = ImageFont.truetype(font_path, size)
    lines = [f"constexpr Glyph {name}[] = {{"]
    for code in codes:
        char = chr(code)
        advance = max(1, round(font.getlength(char)))
        image = Image.new("L", (16, height))
        ImageDraw.Draw(image).text((0, baseline), char, font=font, anchor="ls", fill=255)
        rows = [sum((image.getpixel((x, y)) >= 110) << x for x in range(16))
                for y in range(height)]
        bits = ", ".join(f"0x{row:04x}" for row in rows)
        lines.append(f"    {{ {advance:2}, {{{bits}}} }},")
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font_dir", type=Path)
    args = parser.parse_args()
    ascii_codes = list(range(32, 127))
    body = bitmap(str(args.font_dir / "LiberationSans-Regular.ttf"), 13,
                  ascii_codes + list(range(0x400, 0x460)), "regularGlyphs", 11, 14)
    body += bitmap(str(args.font_dir / "LiberationSans-Bold.ttf"), 22,
                   ascii_codes, "headingGlyphs", 17, 21)
    out = Path(__file__).resolve().parent.parent / "src" / "font.inc"
    out.write_text("// Generated by tools/make-font.py from Liberation Sans.\n" + body)


if __name__ == "__main__":
    main()
